CREATE DATABASE IF NOT EXISTS scamshield_db;
USE scamshield_db;

DROP TABLE IF EXISTS scan_logs;
DROP TABLE IF EXISTS blacklisted_domains;
DROP TABLE IF EXISTS scam_keywords;

CREATE TABLE blacklisted_domains (
    domain_id INT AUTO_INCREMENT PRIMARY KEY,
    domain_name VARCHAR(150) UNIQUE NOT NULL,
    risk_weight INT DEFAULT 40,
    threat_type VARCHAR(100)
);

CREATE TABLE scam_keywords (
    keyword_id INT AUTO_INCREMENT PRIMARY KEY,
    keyword VARCHAR(100) UNIQUE NOT NULL,
    risk_weight INT DEFAULT 20,
    category VARCHAR(60)
);

CREATE TABLE scan_logs (
    scan_id INT AUTO_INCREMENT PRIMARY KEY,
    scan_date DATETIME,
    message_snippet VARCHAR(255),
    risk_score INT,
    verdict VARCHAR(30),
    is_quarantined CHAR(1) DEFAULT 'N'
);

